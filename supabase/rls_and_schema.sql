-- CLASSROOM BEHAVIOR & ATTENDANCE APP: DATABASE SCHEMA & RLS POLICIES
-- =====================================================================
-- Run this script in the Supabase SQL Editor to enforce Row Level Security,
-- cascade deletion constraints, indexes, and attendance calculation functions.

-- 1. TABLES SETUP & CONSTRAINTS
-- ---------------------------------------------------------------------

-- Classes Table
CREATE TABLE IF NOT EXISTS public.classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    teacher_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    min_attendance_percentage INTEGER NOT NULL DEFAULT 75 CHECK (min_attendance_percentage BETWEEN 1 AND 100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Students Table
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    student_number TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT unique_student_number_per_class UNIQUE (class_id, student_number)
);

-- Class Sessions Table
CREATE TABLE IF NOT EXISTS public.class_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
    session_date DATE NOT NULL,
    status TEXT NOT NULL DEFAULT 'conducted',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT unique_session_per_class_date UNIQUE (class_id, session_date)
);

-- Attendance Table
CREATE TABLE IF NOT EXISTS public.attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    class_session_id BIGINT REFERENCES public.class_sessions(id) ON DELETE CASCADE,
    attendance_date DATE NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('present', 'absent', 'late')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT unique_student_attendance_date UNIQUE (student_id, attendance_date)
);

-- Behavior Logs Table
CREATE TABLE IF NOT EXISTS public.behavior_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    teacher_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    points INTEGER NOT NULL CHECK (points != 0),
    reason TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_classes_teacher ON public.classes(teacher_id);
CREATE INDEX IF NOT EXISTS idx_students_class ON public.students(class_id);
CREATE INDEX IF NOT EXISTS idx_class_sessions_class ON public.class_sessions(class_id);
CREATE INDEX IF NOT EXISTS idx_attendance_student ON public.attendance(student_id);
CREATE INDEX IF NOT EXISTS idx_attendance_session ON public.attendance(class_session_id);
CREATE INDEX IF NOT EXISTS idx_behavior_student ON public.behavior_logs(student_id);
CREATE INDEX IF NOT EXISTS idx_behavior_teacher ON public.behavior_logs(teacher_id);

-- ---------------------------------------------------------------------
-- 2. ROW LEVEL SECURITY (RLS) POLICIES
-- ---------------------------------------------------------------------
-- Ensures strict isolation: Teachers can ONLY access and modify
-- their own classes, students, sessions, attendance, and behavior records.

-- Enable RLS on all tables
ALTER TABLE public.classes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.class_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.attendance ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.behavior_logs ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if any to prevent conflicts
DROP POLICY IF EXISTS classes_teacher_all ON public.classes;
DROP POLICY IF EXISTS students_teacher_all ON public.students;
DROP POLICY IF EXISTS class_sessions_teacher_all ON public.class_sessions;
DROP POLICY IF EXISTS attendance_teacher_all ON public.attendance;
DROP POLICY IF EXISTS behavior_logs_teacher_all ON public.behavior_logs;

-- Policy for 'classes': Only the creator/owner teacher can perform CRUD
CREATE POLICY classes_teacher_all ON public.classes
    FOR ALL
    TO authenticated
    USING (teacher_id = auth.uid())
    WITH CHECK (teacher_id = auth.uid());

-- Policy for 'students': Teacher can only view/insert/update/delete students in their own classes
CREATE POLICY students_teacher_all ON public.students
    FOR ALL
    TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.classes
            WHERE classes.id = students.class_id
              AND classes.teacher_id = auth.uid()
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.classes
            WHERE classes.id = students.class_id
              AND classes.teacher_id = auth.uid()
        )
    );

-- Policy for 'class_sessions': Teacher can only manage sessions for their own classes
CREATE POLICY class_sessions_teacher_all ON public.class_sessions
    FOR ALL
    TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.classes
            WHERE classes.id = class_sessions.class_id
              AND classes.teacher_id = auth.uid()
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.classes
            WHERE classes.id = class_sessions.class_id
              AND classes.teacher_id = auth.uid()
        )
    );

-- Policy for 'attendance': Teacher can only view/record attendance for students in their classes
CREATE POLICY attendance_teacher_all ON public.attendance
    FOR ALL
    TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.students
            JOIN public.classes ON classes.id = students.class_id
            WHERE students.id = attendance.student_id
              AND classes.teacher_id = auth.uid()
        )
    )
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM public.students
            JOIN public.classes ON classes.id = students.class_id
            WHERE students.id = attendance.student_id
              AND classes.teacher_id = auth.uid()
        )
    );

-- Policy for 'behavior_logs': Teacher can only view/create behavior logs for students in their classes
CREATE POLICY behavior_logs_teacher_all ON public.behavior_logs
    FOR ALL
    TO authenticated
    USING (
        teacher_id = auth.uid() AND
        EXISTS (
            SELECT 1 FROM public.students
            JOIN public.classes ON classes.id = students.class_id
            WHERE students.id = behavior_logs.student_id
              AND classes.teacher_id = auth.uid()
        )
    )
    WITH CHECK (
        teacher_id = auth.uid() AND
        EXISTS (
            SELECT 1 FROM public.students
            JOIN public.classes ON classes.id = students.class_id
            WHERE students.id = behavior_logs.student_id
              AND classes.teacher_id = auth.uid()
        )
    );

-- ---------------------------------------------------------------------
-- 3. STORED FUNCTION: get_class_attendance_stats
-- ---------------------------------------------------------------------
-- Calculates attendance statistics per student for a given class.
-- Enforces that caller is the teacher who owns the class.

CREATE OR REPLACE FUNCTION public.get_class_attendance_stats(p_class_id BIGINT)
RETURNS TABLE (
    student_id BIGINT,
    student_name TEXT,
    total_sessions BIGINT,
    present_count BIGINT,
    absent_count BIGINT,
    late_count BIGINT,
    attendance_percentage NUMERIC
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    -- Verify teacher ownership
    IF NOT EXISTS (
        SELECT 1 FROM public.classes
        WHERE id = p_class_id AND teacher_id = auth.uid()
    ) THEN
        RAISE EXCEPTION 'Access Denied: You do not own class %', p_class_id;
    END IF;

    RETURN QUERY
    SELECT
        s.id AS student_id,
        s.name AS student_name,
        COUNT(a.id) AS total_sessions,
        COUNT(CASE WHEN a.status = 'present' THEN 1 END) AS present_count,
        COUNT(CASE WHEN a.status = 'absent' THEN 1 END) AS absent_count,
        COUNT(CASE WHEN a.status = 'late' THEN 1 END) AS late_count,
        CASE
            WHEN COUNT(a.id) > 0 THEN
                ROUND((COUNT(CASE WHEN a.status = 'present' THEN 1 END)::NUMERIC / COUNT(a.id)::NUMERIC) * 100, 1)
            ELSE
                0
        END AS attendance_percentage
    FROM
        public.students s
    LEFT JOIN
        public.attendance a ON a.student_id = s.id
    WHERE
        s.class_id = p_class_id
    GROUP BY
        s.id, s.name
    ORDER BY
        s.name ASC;
END;
$$;

